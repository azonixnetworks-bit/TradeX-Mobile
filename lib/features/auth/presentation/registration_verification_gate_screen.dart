
import 'package:flutter/material.dart';

import '../../../core/theme/tradex_design_system.dart';
import 'widgets/auth_form_components.dart';

class RegistrationVerificationGateScreen
    extends StatefulWidget {
  const RegistrationVerificationGateScreen({
    super.key,
    required this.onVerify,
    required this.onBack,
  });

  final Future<void> Function() onVerify;
  final VoidCallback onBack;

  @override
  State<RegistrationVerificationGateScreen> createState() =>
      _RegistrationVerificationGateScreenState();
}

class _RegistrationVerificationGateScreenState
    extends State<RegistrationVerificationGateScreen> {
  bool _loading = false;
  String? _error;

  Future<void> _start() async {
    setState(() {
      _loading = true;
      _error = null;
    });

    try {
      await widget.onVerify();
    } catch (error) {
      if (mounted) {
        setState(() => _error = error.toString());
      }
    } finally {
      if (mounted) {
        setState(() => _loading = false);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return TradeXAuthPage(
      title: 'Verification Gate',
      subtitle:
          'Secure your TradeX account by completing the required verification steps.',

      // FIXED TOP-LEFT BACK ARROW
      onBack: widget.onBack,
      pinBackToTop: true,

      securityDecor: true,

      child: Column(
        children: [
          Container(
            width: 82,
            height: 82,
            decoration: BoxDecoration(
              color: context.palette.goldSoft,
              shape: BoxShape.circle,
              border: Border.all(
                color: context.palette.gold,
              ),
            ),
            child: Icon(
              Icons.shield_outlined,
              color: context.palette.goldText,
              size: 43,
            ),
          ),

          const SizedBox(height: 18),

          const _VerificationStepRow(
            icon: Icons.mail_outline_rounded,
            title: 'Email Verification',
            subtitle:
                'Verify your registered email address',
          ),

          const SizedBox(height: 9),

          const _VerificationStepRow(
            icon: Icons.chat_outlined,
            title: 'WhatsApp Verification',
            subtitle:
                'Verify your registered WhatsApp number',
          ),

          const SizedBox(height: 9),

          const _VerificationStepRow(
            icon: Icons.qr_code_2_rounded,
            title: 'Authenticator Setup',
            subtitle:
                'Link an authenticator app securely',
          ),

          const SizedBox(height: 9),

          const _VerificationStepRow(
            icon: Icons.key_outlined,
            title: 'Recovery Codes',
            subtitle:
                'Save the codes generated by the secure flow',
          ),

          if (_error != null) ...[
            const SizedBox(height: 14),
            Text(
              _error!,
              textAlign: TextAlign.center,
              style: TextStyle(
                color: Theme.of(context)
                    .colorScheme
                    .error,
              ),
            ),
          ],

          const SizedBox(height: 20),

          TradeXGoldButton(
            label: 'Verify Now',
            loading: _loading,
            onPressed: _start,
            icon: Icons.verified_rounded,
          ),
        ],
      ),
    );
  }
}

class _VerificationStepRow extends StatelessWidget {
  const _VerificationStepRow({
    required this.icon,
    required this.title,
    required this.subtitle,
  });

  final IconData icon;
  final String title;
  final String subtitle;

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.symmetric(
        horizontal: 14,
        vertical: 12,
      ),
      decoration: BoxDecoration(
        color: context.palette.surfaceMuted,
        borderRadius: BorderRadius.circular(14),
        border: Border.all(
          color: context.palette.border,
        ),
      ),
      child: Row(
        children: [
          Icon(
            icon,
            color: context.palette.goldText,
            size: 25,
          ),

          const SizedBox(width: 12),

          Expanded(
            child: Column(
              crossAxisAlignment:
                  CrossAxisAlignment.start,
              children: [
                Text(
                  title,
                  style: TextStyle(
                    color:
                        context.palette.primaryText,
                    fontWeight: FontWeight.w800,
                  ),
                ),

                const SizedBox(height: 2),

                Text(
                  subtitle,
                  style: TextStyle(
                    color:
                        context.palette.secondaryText,
                    fontSize: 12,
                  ),
                ),
              ],
            ),
          ),

          Icon(
            Icons.chevron_right_rounded,
            color: context.palette.secondaryText,
          ),
        ],
      ),
    );
  }
}
